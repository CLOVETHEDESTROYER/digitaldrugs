#!/usr/bin/env python3
"""Original feedback-first MilkDrop presets. Independent from native Metal scenes."""
from pathlib import Path
import json,sys
root=Path(__file__).resolve().parents[1]/'Sources/ZenWaveStudio/Resources/Butterchurn'
header='''
vec3 inkColor(float x){return 0.52+0.46*cos(vec3(.1,2.15,4.25)+x*6.2831853);}
mat2 inkRot(float a){return mat2(cos(a),sin(a),-sin(a),cos(a));}
float inkNoise(vec2 p){return sin(p.x+sin(p.y*1.31))*sin(p.y+sin(p.x*.87));}
float inkFbm(vec2 p){float n=0.0;float a=.5;for(int i=0;i<4;i++){n+=inkNoise(p)*a;p=inkRot(.61)*p*1.92+vec2(2.1,1.7);a*=.5;}return n;}
vec3 inkSeed(vec2 p,float t,float drive,int kind){
 float r=length(p),a=atan(p.y,p.x);vec3 c=vec3(.001,.003,.012);
 if(kind==0){
  float flow=inkFbm(p*6.0+vec2(t*.06,-t*.04));
  float ridge=exp(-abs(sin(flow*11.0+p.y*3.0-t*.12))*25.0);
  c+=inkColor(flow*.6+t*.013)*(ridge*.45+.045+pow(.5+.5*flow,2.0)*.22);
 }else if(kind==1){
  float winding=a+log(r+.035)*2.8-t*.13;
  float stream=pow(.5+.5*sin(winding*7.0+inkNoise(p*8.0+t*.03)),14.0);
  c+=inkColor(log(r+.04)*.17+t*.015)*stream*.60*smoothstep(.025,.12,r)*exp(-r*.7);
 }else if(kind==2){
  vec2 q=p*7.0+vec2(sin(t*.07),cos(t*.09));
  float n=inkFbm(q+vec2(inkFbm(q+t*.025),inkFbm(q-3.0-t*.025))*2.0);
  float band=pow(.5+.5*cos(n*23.0+t*.16),7.0);
  c+=inkColor(n*.8+t*.009)*(band*.38+.04);
 }else if(kind==3){
  vec2 q=inkRot(t*.025)*p;
  float lace=abs(sin(q.x*19.0+sin(q.y*5.0-t*.18))*sin(q.y*19.0+sin(q.x*5.0+t*.18)));
  float thread=exp(-lace*45.0);
  c+=inkColor(length(q)*.7+t*.01)*thread*.42;
 }else if(kind==4){
  for(int i=0;i<7;i++){float k=float(i);float y=p.y-(k-3.0)*.105-sin(p.x*5.0+t*.4+k*.6)*(.04+drive*.025)-sin(p.x*13.0-t*.18+k)*.018;
   c+=inkColor(k*.13+t*.01)*exp(-y*y/.00009)*.55;}
 }else if(kind==5){
  float folded=abs(fract(a/1.04719755+.5)-.5)*1.04719755;
  vec2 q=vec2(cos(folded),sin(folded))*r;
  float n=inkFbm(q*9.0+vec2(t*.025,-t*.04));
  float flower=pow(.5+.5*cos(r*36.0+n*6.0-t*.3),10.0);
  c+=inkColor(r*.6+n*.2+t*.012)*flower*.45;
 }else if(kind==6){
  for(int j=0;j<5;j++){float k=float(j);float radius=.11+k*.058+.045*cos(a*(5.0+k)+t*.15+k);
   float d=r-radius;float ribbon=exp(-d*d/.00016);
   c+=inkColor(k*.18+a*.06+t*.01)*ribbon*.36;}
 }else{
  for(int j=0;j<5;j++){float k=float(j);float ridge=p.x-(k-2.0)*.13-sin(p.y*3.5+t*.1+k)*.15;
   float light=exp(-ridge*ridge/.0025)*(.55+.45*sin(p.y*8.0-t*.3+k));
   c+=inkColor(k*.18+p.y*.12+t*.007)*light*.20;}
 }
 return c*(.85+drive*.45);
}
'''
names=['Opal Ink','Velvet Vortex','Chromaflow','Neon Lace','Electric Tide','Mandala Echo','Spectral Petals','Aurora Memory']
warps=[
 'q+=vec2(inkFbm(p*5.0+time*.025),inkFbm(p*5.0+4.0-time*.025))*.006;',
 'q=inkRot(.009/(length(p)+.2))*q*.996;',
 'q+=vec2(sin(p.y*7.0+time*.08),cos(p.x*7.0-time*.07))*.003;',
 'q=inkRot(.002)*q*.998+vec2(sin(p.y*16.0),sin(p.x*16.0))*.0007;',
 'q.y+=.002*sin(p.x*8.0+time*.15);q.x*=.998;',
 'q=inkRot(.004)*q*.994;',
 'q=inkRot(-.004)*q*(.996+.001*sin(atan(p.y,p.x)*6.0+time*.08));',
 'q.y+=.0015;q.x+=.002*sin(p.y*4.0+time*.08);'
]
entries=[]
for kind,name in enumerate(names):
 common=f'vec2 p=(uv-.5)*aspect.xy/max(min(aspect.x,aspect.y),.25);\nvec3 seed=inkSeed(p,time,clamp(vol*.4,0.0,1.0),{kind});\n'
 warp=header+'\nshader_body {\n'+common+'vec2 q=uv-.5;\n'+warps[kind]+'''\nvec3 memory=texture(sampler_main,q+.5).rgb;
ret=memory*.965+seed*.075;
}\n'''
 comp=header+'\nshader_body {\n'+common+'''vec2 offset=vec2(.0008,-.0005);
vec3 memory=texture(sampler_main,uv).rgb;
memory.r=texture(sampler_main,uv+offset).r;
memory.b=texture(sampler_main,uv-offset).b;
ret=1.0-exp(-(memory*.68+seed*.44)*2.2);
}\n'''
 preset=dict(baseVals=dict(decay=.96,gammaadj=1,zoom=1,rot=0,warp=0,wave_a=0,ob_a=0,ib_a=0,mv_a=0,bmotionvectorson=0,echo_alpha=0,darken_center=0,fshader=0),shapes=[],waves=[],init_eqs_str='',frame_eqs_str='',pixel_eqs_str='',warp=warp,comp=comp)
 entries.append(dict(id=f'zenwave-showcase-{kind+1}',title=name,collection='showcase',reviewMetalStyle=40+kind,authorPreset=f'ZenWave original · {name}',preset=preset))
contents='// Generated by Tools/generate-showcase-presets.py. Original feedback-first shaders.\nwindow.ZenWavePresets.push(...'+json.dumps(entries,separators=(',',':'),ensure_ascii=False)+');\n'
output=root/'showcase-presets.js'
if '--check' in sys.argv:
 if not output.exists() or output.read_text()!=contents:raise SystemExit('Run Tools/generate-showcase-presets.py before building.')
else:output.write_text(contents)
print('Verified' if '--check' in sys.argv else 'Generated','eight original Butterchurn Showcase presets.')
