#!/usr/bin/env python3
"""Generate original GLSL/MilkDrop scenes from our Metal scene math. No dependencies."""
from pathlib import Path
import json, sys
studio = Path(__file__).resolve().parents[1]
resources = studio / 'Sources/ZenWaveStudio/Resources'
metal = (resources / 'SpaceJourneys.metal').read_text()
glsl = metal.replace('float2', 'vec2').replace('float3', 'vec3').replace('atan2(', 'atan(')
scenes = ['Event Horizon', 'Aurora Slipstream', 'Crystal Stargate', 'Nebula Drift']
entries = []
for kind, title in enumerate(scenes):
    scene = f'''vec2 p = (uv - 0.5) * aspect.xy / max(min(aspect.x, aspect.y), 0.25);
vec3 scene = spaceJourney(p, time, clamp(vol * 0.4, 0.0, 1.0), clamp(bass * 0.4, 0.0, 1.0), clamp(treb * 0.4, 0.0, 1.0), 1.0, {kind});'''
    warp = glsl + '\nshader_body {\n' + scene + '''
vec2 trailUV = (uv - 0.5) * 0.997 + 0.5;
ret = texture(sampler_main, trailUV).rgb * 0.90 + scene * 0.10;
}\n'''
    comp = glsl + '\nshader_body {\n' + scene + '''
ret = scene * 0.68 + texture(sampler_main, uv).rgb * 0.32;
}\n'''
    preset = dict(baseVals=dict(decay=0.94, gammaadj=1, zoom=1, rot=0, warp=0, wave_a=0,
                               ob_a=0, ib_a=0, mv_a=0, bmotionvectorson=0, echo_alpha=0,
                               darken_center=0, fshader=0), shapes=[], waves=[], init_eqs_str='',
                  frame_eqs_str='', pixel_eqs_str='', warp=warp, comp=comp)
    entries.append(dict(id=f'zenwave-space-{kind + 1}', title=title, collection='space',
                        metalStyle=36 + kind, authorPreset=f'ZenWave original · {title}', preset=preset))
output = resources / 'Butterchurn/space-presets.js'
contents = ('// Generated by Tools/generate-space-presets.py from SpaceJourneys.metal.\n'
                  'window.ZenWavePresets.push(...' + json.dumps(entries, ensure_ascii=False, separators=(',', ':')) + ');\n')
if '--check' in sys.argv:
    if not output.exists() or output.read_text() != contents:
        raise SystemExit('Space preset sources differ. Run Tools/generate-space-presets.py before building.')
else:
    output.write_text(contents)
print('Verified' if '--check' in sys.argv else 'Generated', 'four original Butterchurn space presets.')
